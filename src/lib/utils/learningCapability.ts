export const getCapabilitySuggestionPrompts = (
	selectedCapability: string | null | undefined,
	fallbackPrompts: PromptSuggestion[] = []
): PromptSuggestion[] => {
	if (!selectedCapability || !CAPABILITY_SUGGESTIONS[selectedCapability]) {
		return fallbackPrompts;
	}

	const focused = CAPABILITY_SUGGESTIONS[selectedCapability];
	const merged = [...focused, ...fallbackPrompts];
	const deduped: PromptSuggestion[] = [];
	const seen = new Set<string>();

	for (const item of merged) {
		const key = `${item.title?.join('::') ?? ''}::${item.content}`;
		if (!seen.has(key)) {
			seen.add(key);
			deduped.push(item);
		}
	}

	return deduped;
};